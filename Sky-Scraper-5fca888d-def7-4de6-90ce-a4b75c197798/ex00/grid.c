#include "rush01.h"

void	init_grid(void)
{
	int	i;
	int	j;

	i = 0;
	while (i < 4)
	{
		j = 0;
		while (j < 4)
		{
			g_grid[i][j] = 0;
			j++;
		}
		i++;
	}
}
