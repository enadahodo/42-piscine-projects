#include "rush01.h"

void	print_grid(void)
{
	int	i;
	int	j;

	i = 0;
	while (i < 4)
	{
		j = 0;
		while (j < 4)
		{
			write(1, &"0123456789"[g_grid[i][j]], 1);
			if (j < 3)
				write(1, " ", 1);
			j++;
		}
		write(1, "\n", 1);
		i++;
	}
}

void	print_error(void)
{
	write(1, "Error\n", 6);
}
